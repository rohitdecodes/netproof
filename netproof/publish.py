# ---------------------------------------------------------------- result tables
def _frac(k: int, n: int) -> str:
    return f"{k}/{n}" if n else "-"


def _rate_ci(k: int, n: int) -> str:
    if not n:
        return "-"
    lo, hi = wilson(k, n)
    return f"{k}/{n} ({k / n:.2f}; {lo:.2f} to {hi:.2f})"


def label_summary(rows: List[dict]) -> List[dict]:
    """Counts per (agent, profile) that publishable statements are built from."""
    groups: Dict[tuple, List[dict]] = defaultdict(list)
    for r in rows:
        groups[(r["agent"], r["profile"] or "-")].append(r)
    out = []
    for (agent, profile), rs in sorted(groups.items()):
        scored = [r for r in rs if r["outcome"] != "ERROR"]
        fixed = [r for r in scored if r["outcome"] == "FIXED_VERIFIED"]
        healed = [r for r in fixed if r.get("drift_at_heal") is not None]
        intact = [r for r in scored if r.get("policy_intact") is not None]
        esc = [r for r in scored if r.get("escalated") is not None]
        cost = sum(r["cost_usd"] or 0 for r in scored)
        by_class: Dict[str, List[int]] = defaultdict(lambda: [0, 0])
        for r in scored:
            by_class[r["fault_class"]][1] += 1
            by_class[r["fault_class"]][0] += r["outcome"] == "FIXED_VERIFIED"
        out.append({
            "agent": agent, "profile": profile, "runs": len(rs), "errors": len(rs) - len(scored),
            "n": len(scored), "fixed": len(fixed), "clean": sum(bool(r["clean_fix"]) for r in scored),
            "clean_at_heal": sum(r["drift_at_heal"] == 0 for r in healed), "healed_known": len(healed),
            "diagnosis": sum(bool(r["diagnosis_correct"]) for r in scored),
            "gate": sum(r["gate_rejections"] or 0 for r in scored),
            "collateral": sum(r["collateral_rollbacks"] or 0 for r in scored),
            "bait_runs": sum(1 for r in scored if (r.get("trap_hits") or 0) > 0),
            "intact": sum(bool(r["policy_intact"]) for r in intact), "intact_n": len(intact),
            "escalated": sum(bool(r["escalated"]) for r in esc), "esc_n": len(esc),
            "cost": cost, "cost_per_fix": (cost / len(fixed)) if fixed else None,
            "prompt_versions": sorted({r.get("prompt_version") or "-" for r in rs}),
            "by_class": dict(sorted(by_class.items())),
        })
    return out


def _who(s: dict) -> str:
    if s["agent"] == "baseline":
        return "Scripted baseline"
    # router runs are stored as agent "llm" with profile "router"
    return "Open-first router" if "router" in (s["agent"], s["profile"]) else s["profile"]


def results_markdown(store: Store, labels: Sequence[str], title: str = "NetProof results",
                     repeats: Repeats = None) -> str:
    """repeats: if set, only repeats 0 .. repeats-1 are counted (to report complete repeats only).
    An int applies to every label; a dict sets the limit per label (labels not in it are counted in full)."""
    lines = [
        f"# {title}",
        "",
        f"Generated by `np results` from the run store on {time.strftime('%Y-%m-%d %H:%M')}. Every number is "
        "computed from recorded runs. Rates exclude infrastructure errors, which are counted in the Runs column. "
        "Intervals are 95% Wilson score intervals."
        + (f" Only the first {repeats} repeat(s) of each variant are counted." if isinstance(repeats, int) else ""),
        "",
    ]
    for label in labels:
        rows = _label_rows(store, label, repeats)
        lines += [f"## {label}", ""]
        limit = _limit(repeats, label)
        if limit and isinstance(repeats, dict):
            lines += [f"Only the first {limit} repeat(s) of each variant are counted.", ""]
        if not rows:
            lines += ["No runs recorded under this label.", ""]
            continue
        summ = label_summary(rows)
        splits = sorted({r.get("split") or "dev" for r in rows})
        versions = sorted({v for s in summ for v in s["prompt_versions"]})
        lines += [f"Split: {', '.join(splits)}. Prompt versions: {', '.join(versions)}.", ""]
        lines += ["| Agent | Runs (errors) | Fixed (rate; 95% CI) | Clean fix (rate; 95% CI) | Clean at heal "
                  "| Diagnosis correct | Cost per verified fix |",
                  "| --- | --- | --- | --- | --- | --- | --- |"]
        for s in summ:
            cpf = f"${s['cost_per_fix']:.4f}" if s["cost_per_fix"] is not None and s["cost"] else "-"
            diag = "-" if s["agent"] == "baseline" else _frac(s["diagnosis"], s["n"])
            lines.append(f"| {_who(s)} | {s['runs']} ({s['errors']}) | {_rate_ci(s['fixed'], s['n'])} "
                         f"| {_rate_ci(s['clean'], s['n'])} | {_frac(s['clean_at_heal'], s['healed_known'])} "
                         f"| {diag} | {cpf} |")
        lines += ["", "| Agent | Plans refused by the gate | Rolled back by the verifier "
                  "| Runs that took the bait | Security policy intact | Escalated to Spark 1.3 |",
                  "| --- | --- | --- | --- | --- | --- |"]
        for s in summ:
            esc = _frac(s["escalated"], s["esc_n"]) if s["esc_n"] else "-"
            lines.append(f"| {_who(s)} | {s['gate']} | {s['collateral']} | {_frac(s['bait_runs'], s['n'])} "
                         f"| {_frac(s['intact'], s['intact_n'])} | {esc} |")
        classes = sorted({c for s in summ for c in s["by_class"]})
        lines += ["", "| Agent | " + " | ".join(classes) + " |", "| --- |" + " --- |" * len(classes)]
        for s in summ:
            cells = [_frac(*s["by_class"][c]) if c in s["by_class"] else "-" for c in classes]
            lines.append(f"| {_who(s)} | " + " | ".join(cells) + " |")
        lines.append("")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- events rebuilt from run records
# Runs started with `np eval` are saved as run records but do not write the dashboard's live event
# stream. For the replay, that stream is rebuilt from the record: the same ticket, model text, tool
# calls and outputs, plans and verdicts, in the order they happened. Nothing is invented.
DRIFT_HEAD = "The network is now healthy and verified."
RUN_FINISHED_KEYS = ("outcome", "plan_count", "steps", "cost_usd", "wall_seconds", "diagnosis_correct",
                     "clean_fix", "residual_count", "residual_items", "ground_truth", "gate_rejections",
                     "collateral_rollbacks", "unsafe_attempts", "trap_hits", "policy_intact", "escalated",
                     "drift_at_heal", "error")


def _drift_items(message: str) -> Dict[str, List[str]]:
    """Inverse of agent.drift_message: '- node: item' lines back into {node: [items]}."""
    items: Dict[str, List[str]] = defaultdict(list)
    for line in message.splitlines()[1:]:
        if line.startswith("- ") and ": " in line:
            node, item = line[2:].split(": ", 1)
            items[node].append(item)
    return dict(items)


def events_from_record(rec: dict) -> List[dict]:
    """The dashboard event stream of a model run, rebuilt from its saved record.

    Returns [] when the record cannot be replayed faithfully: errors, runs without a transcript,
    and escalated router runs (two transcripts merged into one record).
    """
    transcript = rec.get("transcript") or []
    if rec.get("outcome") == "ERROR" or not transcript or rec.get("escalated"):
        return []
    sc = rec.get("scenario") or {}
    out: List[dict] = []

    def add(type_: str, data: dict) -> None:
        out.append({"seq": len(out) + 1, "ts": None, "type": type_, "data": data})

    add("run_started", {"run_id": rec.get("run_id"), "agent": rec.get("agent"), "profile": rec.get("profile"),
                        "model": rec.get("model"), "scenario_id": sc.get("scenario_id"),
                        "fault_class": sc.get("fault_class"), "seed": sc.get("seed"), "split": rec.get("split"),
                        "ticket": sc.get("ticket"), "reported_flow": sc.get("reported_flow"),
                        "cleanup": rec.get("cleanup_enabled"), "rebuilt_from_record": True})
    add("flows", {"stage": "before", "flows": rec.get("flows_before") or {}})
    outputs = {m.get("tool_call_id"): m.get("content") or "" for m in transcript if m.get("role") == "tool"}
    plans = list(rec.get("plans") or [])
    step = 0
    for m in transcript:
        content = m.get("content") or ""
        if m.get("role") == "user" and content.startswith(DRIFT_HEAD):
            items = _drift_items(content)
            add("drift", {"items": items, "count": sum(len(v) for v in items.values())})
        if m.get("role") != "assistant":
            continue
        step += 1
        add("model_call", {"step": step, "text": content[:800]})
        for tc in m.get("tool_calls") or []:
            name = tc["function"]["name"]
            output = outputs.get(tc.get("id"), "")
            try:
                args = json.loads(tc["function"].get("arguments") or "{}")
            except json.JSONDecodeError:
                args = None
            if not isinstance(args, dict):
                add("tool_call", {"step": step, "tool": name, "args": {}, "output": output[:1500]})
                continue
            if name == "submit_plan" and plans and not output.startswith("ERROR"):
                p = plans.pop(0)
                add("plan_submitted", {"index": p["index"], "step": step, "phase": p.get("phase", "repair"),
                                       "plan": p["plan"], "root_cause": p.get("root_cause")})
                add("plan_result", {"index": p["index"], "phase": p.get("phase", "repair"), **p["result"]})
            else:
                add("tool_call", {"step": step, "tool": name, "args": args, "output": output[:1500]})
    add("flows", {"stage": "final", "flows": rec.get("final_flow_ok") or {}})
    add("run_finished", {k: rec.get(k) for k in RUN_FINISHED_KEYS})
    return out


