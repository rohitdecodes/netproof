def _banner(featured: List[Tuple[str, str]]) -> str:
    buttons = "".join(f'<button class="featured" data-run="{html.escape(rid)}">{html.escape(title)}</button>'
                      for rid, title in featured)
    return ('<div class="replay-banner"><p><strong>Read-only replay of recorded NetProof runs.</strong> '
            "Nothing here calls a model or touches a network; clone the repository to run the lab yourself. "
            "Pick a featured run, any run on the left, or the Scoreboard tab.</p>" + buttons + "</div>")


def _transform_index(src: str, featured: List[Tuple[str, str]]) -> str:
    out = src
    for old, new in (('href="/static/style.css"', 'href="style.css"'),
                     ('<script src="/static/app.js"></script>',
                      '<script src="replay.js"></script>\n  <script src="app.js"></script>'),
                     ("<body>", "<body>\n  " + _banner(featured))):
        if old not in out:
            raise ValueError(f"web/index.html does not contain {old!r}; update publish.py to match it")
        out = out.replace(old, new, 1)
    return out


REPORT_LINK_OLD = "/api/runs/${encodeURIComponent(S.runId)}/report"
REPORT_LINK_NEW = "data/reports/${encodeURIComponent(S.runId)}.html"


def _transform_app(src: str) -> str:
    if REPORT_LINK_OLD not in src:
        raise ValueError(f"web/app.js does not contain {REPORT_LINK_OLD!r}; update publish.py to match it")
    return src.replace(REPORT_LINK_OLD, REPORT_LINK_NEW)


def _write_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=1, default=str), encoding="utf-8", newline="\n")


def export_site(store: Store, out_dir: Path, labels: Sequence[str] = (), replay_labels: Sequence[str] = (),
                featured: Sequence[Tuple[str, str]] = (), web_dir: Optional[Path] = None) -> dict:
    """Write a static site that replays recorded runs with the dashboard's own code.

    labels: scoreboards to include. replay_labels: labels whose runs get full event replays.
    featured: (run_id, title) pairs shown as buttons; their events are always included.
    """
    web = Path(web_dir or WEB_DIR)
    out = Path(out_dir)
    if out.exists():
        shutil.rmtree(out)
    data = out / "data"
    (data / "events").mkdir(parents=True)
    (data / "reports").mkdir(parents=True)

    run_ids: List[str] = []
    for rid, _ in featured:
        if store.get_run(rid) is None:
            raise ValueError(f"featured run {rid} is not in the run store")
        run_ids.append(rid)
    for label in replay_labels:
        for r in store.list_runs(limit=1_000_000, label=label):
            if r["run_id"] not in run_ids:
                run_ids.append(r["run_id"])

    titles = dict(featured)
    rows_out = []
    for rid in run_ids:
        row = store.get_run(rid)
        events = [e for e in store.events(rid) if e["type"] != "saved"]
        if not events:
            continue
        _write_json(data / "events" / f"{rid}.json", events)
        report_path = row.get("report_path")
        if report_path and Path(report_path).exists():
            body = html.escape(Path(report_path).read_text(encoding="utf-8"))
            (data / "reports" / f"{rid}.html").write_text(REPORT_HTML.format(title=html.escape(rid), body=body),
                                                         encoding="utf-8", newline="\n")
        clean = {k: v for k, v in row.items() if k not in PRIVATE_COLUMNS}
        clean["featured_title"] = titles.get(rid)
        rows_out.append(clean)
    _write_json(data / "runs.json", rows_out)

    all_rows = []
    for label in labels:
        rows = store.list_runs(limit=1_000_000, label=label)
        all_rows += rows
        _write_json(data / "scoreboard" / f"{quote(label, safe='')}.json",
                    {"label": label, "evals": store.eval_ids_for_label(label), "rows": scoreboard(rows)})
    _write_json(data / "scoreboard" / "_all.json", {"evals": list(labels), "rows": scoreboard(all_rows)})
    _write_json(data / "labels.json", list(labels))

    topo, flows = load_topology(), load_intent()
    _write_json(data / "topology.json", {
        "nodes": [{"name": n, "role": node.role, "interfaces": node.interfaces} for n, node in topo.nodes.items()],
        "networks": {k: {"subnet": v["subnet"]} for k, v in topo.networks.items()},
        "flows": [f.__dict__ for f in flows]})
    for split, cat in SPLITS.items():
        _write_json(data / f"catalog-{split}.json",
                    {c: [{"seed": i, "variant": v.key, "reported_flow": v.reported_flow} for i, v in enumerate(vs)]
                     for c, vs in cat.items()})
    prof = load_profiles()
    _write_json(data / "profiles.json", {"default": prof.get("default"),
                                         "profiles": [{"name": k, "model": v["model"], "key_present": False}
                                                      for k, v in prof.get("profiles", {}).items()]})

    (out / "index.html").write_text(_transform_index((web / "index.html").read_text(encoding="utf-8"),
                                                     list(featured)), encoding="utf-8", newline="\n")
    (out / "app.js").write_text(_transform_app((web / "app.js").read_text(encoding="utf-8")),
                                encoding="utf-8", newline="\n")
    (out / "style.css").write_text((web / "style.css").read_text(encoding="utf-8") + REPLAY_CSS,
                                   encoding="utf-8", newline="\n")
    shutil.copyfile(web / "replay.js", out / "replay.js")
    (out / ".nojekyll").write_text("", encoding="utf-8")
    size = sum(f.stat().st_size for f in out.rglob("*") if f.is_file())
    return {"runs": len(rows_out), "labels": list(labels), "bytes": size}


def leaks(site_dir: Path, needles: Sequence[str]) -> List[str]:
    """Files in the exported site that contain any of `needles` (local paths, user names)."""
    found = []
    for f in Path(site_dir).rglob("*"):
        if f.is_file():
            text = f.read_text(encoding="utf-8", errors="ignore")
            for n in needles:
                if n and n in text:
                    found.append(f"{f.relative_to(site_dir)}: {n}")
    return found
